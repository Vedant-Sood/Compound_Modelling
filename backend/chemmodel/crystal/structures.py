def build_reference(name: str, cellpar: list[float] | None = None) -> Structure:
    """Conventional cell of a reference crystal, optionally with edited lattice parameters."""
    from ase.spacegroup import crystal

    try:
        ref = REFERENCE_STRUCTURES[name]
    except KeyError as exc:
        raise ValueError(f"unknown reference structure {name!r}") from exc
    symbols = [s for s, _ in ref["basis"]]
    basis = [p for _, p in ref["basis"]]
    atoms = crystal(symbols, basis=basis, spacegroup=ref["spacegroup"], cellpar=cellpar or ref["cellpar"])
    return Structure.from_ase(atoms)


def from_cellpar(cellpar: list[float], species: list[str], frac: list[list[float]], spacegroup: int | None = None) -> Structure:
    """User-defined crystal: lattice parameters a, b, c (Å), α, β, γ (°) and a basis,
    optionally expanded by a space group (1-230)."""
    from ase.geometry import cellpar_to_cell
    from ase.spacegroup import crystal

    if len(cellpar) != 6:
        raise ValueError("cellpar must be [a, b, c, alpha, beta, gamma]")
    a, b, c, al, be, ga = cellpar
    if min(a, b, c) <= 0 or not all(0 < x < 180 for x in (al, be, ga)):
        raise ValueError("lengths must be positive and angles between 0 and 180°")
    if spacegroup:
        atoms = crystal(species, basis=frac, spacegroup=int(spacegroup), cellpar=cellpar)
        return Structure.from_ase(atoms)
    return Structure.from_json({"cell": cellpar_to_cell(cellpar).tolist(), "species": species, "frac_coords": frac})
