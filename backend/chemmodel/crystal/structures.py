"""Periodic structures: JSON exchange format and reference crystals.

A structure is exchanged as JSON::

    {"cell": [[ax, ay, az], [bx, by, bz], [cx, cy, cz]],   # Å, rows are lattice vectors
     "species": ["Na", "Cl", ...],
     "frac_coords": [[x, y, z], ...],                        # fractional
     "pbc": [true, true, true]}

Reference structures use experimental room-temperature lattice parameters
with the source stated in each entry. They are built from the space group
and Wyckoff positions, so the full conventional cell is generated by
symmetry rather than typed in.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np


@dataclass
class Structure:
    cell: np.ndarray  # (3, 3) Å, rows = a, b, c
    species: list[str]
    frac: np.ndarray  # (n, 3)
    pbc: tuple[bool, bool, bool] = (True, True, True)

    @classmethod
    def from_json(cls, d: dict) -> "Structure":
        from ase.data import atomic_numbers

        cell = np.array(d["cell"], dtype=float).reshape(3, 3)
        species = [str(s).strip().capitalize() for s in d["species"]]
        frac = np.array(d["frac_coords"], dtype=float).reshape(-1, 3)
        if len(species) != len(frac) or not species:
            raise ValueError("species and frac_coords must be non-empty and the same length")
        unknown = sorted({s for s in species if atomic_numbers.get(s, 0) == 0})
        if unknown:
            raise ValueError(f"unknown element symbol(s): {', '.join(unknown)}")
        if not (np.isfinite(cell).all() and np.isfinite(frac).all()):
            raise ValueError("cell and coordinates must be finite")
        vol = abs(np.linalg.det(cell))
        if vol < 1.0:
            raise ValueError(f"cell volume {vol:.3g} Å³ is degenerate")
        pbc = tuple(bool(x) for x in d.get("pbc", (True, True, True)))
        return cls(cell, species, frac, pbc)  # type: ignore[arg-type]

    def to_json(self) -> dict:
        return {
            "cell": self.cell.tolist(),
            "species": list(self.species),
            "frac_coords": self.frac.tolist(),
            "pbc": list(self.pbc),
        }

    def to_ase(self):
        from ase import Atoms

        return Atoms(self.species, scaled_positions=self.frac, cell=self.cell, pbc=self.pbc)

    @classmethod
    def from_ase(cls, atoms) -> "Structure":
        return cls(
            np.array(atoms.cell[:]),
            list(atoms.get_chemical_symbols()),
            np.array(atoms.get_scaled_positions(wrap=True)),
            tuple(bool(x) for x in atoms.pbc),  # type: ignore[arg-type]
        )

    @property
    def cartesian(self) -> np.ndarray:
        return self.frac @ self.cell


